# ---------------------------------------------------------------------------
# Core function: find commit SHA for a given component version
#
# Uses git log -S to find the commit that first introduced the ## [X.Y.Z]
# header in the component's CHANGELOG.md. The --reverse flag combined with
# head -1 gives the OLDEST (first) matching commit.
#
# Args:
#   $1 — component path relative to repo root (e.g., agents/frankenstein)
#   $2 — version string (e.g., 1.5.0)
#
# Outputs:
#   One line: "{sha} {author-date} {subject}" or empty string if not found
# ---------------------------------------------------------------------------
find_version_commit() {
  local component_path="$1"
  local version="$2"
  local search_string="## [${version}]"
  local changelog="${REPO_ROOT}/${component_path}/CHANGELOG.md"

  if [[ ! -f "$changelog" ]]; then
    echo ""
    return
  fi

  # --reverse --all: scan entire history across all refs, oldest first
  # -S: pickaxe — finds commits that added/removed the string
  # head -1: take the oldest (first) such commit
  # Note: --diff-filter=A is intentionally NOT used here; it would restrict to
  #   commits that created the file from scratch, missing version headers that
  #   were added as modifications to an already-existing CHANGELOG.md.
  #
  # || true: prevents set -e from aborting when git log receives SIGPIPE
  #   because head -1 closes its end of the pipe after reading one line.
  git -C "${REPO_ROOT}" log \
    --reverse \
    --all \
    -S "${search_string}" \
    --format="%H %ai %s" \
    -- "${component_path}/CHANGELOG.md" 2>/dev/null | head -1 || true
}

# ---------------------------------------------------------------------------
# Core function: emit a tag command or a MANUAL REVIEW placeholder
#
# Args:
#   $1 — component slug (e.g., frankenstein)
#   $2 — component path relative to repo root (e.g., agents/frankenstein)
#   $3 — version string (e.g., 1.5.0)
# ---------------------------------------------------------------------------
emit_tag_command() {
  local slug="$1"
  local component_path="$2"
  local version="$3"
  local tag="${slug}-v${version}"

  local commit_line
  commit_line=$(find_version_commit "${component_path}" "${version}")

  if [[ -z "$commit_line" ]]; then
    echo "# MANUAL REVIEW REQUIRED: ${tag} — no historical commit found for '## [${version}]' in ${component_path}/CHANGELOG.md"
    echo "# git tag -a ${tag} <SHA-HERE> -m \"${slug} ${version}\""
    echo ""
    return
  fi

  local sha date_field subject
  sha=$(echo "$commit_line" | awk '{print $1}')
  date_field=$(echo "$commit_line" | awk '{print $2}')
  subject=$(echo "$commit_line" | awk '{$1=$2=$3=""; sub(/^[[:space:]]+/, ""); print}')
  # Truncate subject to 60 chars for readability
  subject="${subject:0:60}"

  # Comment block: provenance info
  echo "# component: ${component_path}"
  echo "# version:   ${version}"
  echo "# found by:  git log -S '## [${version}]' -- ${component_path}/CHANGELOG.md"
  echo "git tag -a ${tag} ${sha} -m \"${slug} ${version}\"   # ${date_field} ${subject}"
  echo ""
}


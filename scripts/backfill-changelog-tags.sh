#!/usr/bin/env bash
# =============================================================================
# backfill-changelog-tags.sh
#
# PURPOSE:
#   Retroactively create per-component git tags for all historical versions
#   across all 47 components in the agent-toolkit monorepo.
#
# SAFETY — EMIT-ONLY, NEVER EXECUTES:
#   This script ONLY PRINTS git tag commands to stdout. It never runs them.
#   Review the output carefully before executing any of it.
#
#   DO NOT RUN this script without reviewing the output first.
#   Tags cannot be deleted from remote once pushed without explicit force.
#
# TAG FORMAT:
#   {component-slug}-v{version}  (e.g., frankenstein-v1.5.0, changelog-v1.2.0)
#   Slug = leaf directory name of the component (all 47 are globally unique).
#
# WARNING: Run this script against a stable repository history. If you rebase,
#   squash, or rewrite history AFTER creating these tags and pushing to origin,
#   the tag SHAs will diverge from the live commits. Verify repo history is stable
#   with `git log --oneline main | head -20` before running.
#
# USAGE:
#   # Step 1 — generate and review
#   ./scripts/backfill-changelog-tags.sh > tags-to-create.sh
#   less tags-to-create.sh
#
#   # Step 2 — execute after review (each tag on its own line in the output)
#   bash tags-to-create.sh
#
#   # Step 3 — push to remote (human runs this after verifying)
#   git push origin --tags
#
#   # Help:
#   ./scripts/backfill-changelog-tags.sh --help
#
# MANUAL REVIEW REQUIRED entries:
#   For any version whose ## [X.Y.Z] header cannot be found in git history
#   (e.g., changelog-v2.0.0, which is being created by the current pipeline
#   and does not yet exist in any commit), the script emits a commented
#   placeholder starting with:
#     # MANUAL REVIEW REQUIRED: ...
#   These are expected and are NOT bugs. The human operator must locate the
#   correct SHA manually and create the tag themselves.
#
# =============================================================================

set -euo pipefail

# ---------------------------------------------------------------------------
# Argument parsing
# ---------------------------------------------------------------------------

for arg in "$@"; do
  case "$arg" in
    --help|-h)
      sed -n '/^# ====/,/^# ====/p' "$0"
      exit 0
      ;;
    *)
      echo "ERROR: unknown argument: $arg" >&2
      echo "Usage: $0 [--help]" >&2
      exit 1
      ;;
  esac
done

# ---------------------------------------------------------------------------
# Locate repo root
# ---------------------------------------------------------------------------
REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
  echo "ERROR: not inside a git repository" >&2
  exit 1
}

# ---------------------------------------------------------------------------
# Shallow-clone guard (DA-007)
# History archaeology requires full git log; shallow clones silently truncate.
# ---------------------------------------------------------------------------
if [[ "$(git rev-parse --is-shallow-repository 2>/dev/null)" == "true" ]]; then
  echo "ERROR: This is a shallow clone. History archaeology requires full git log." >&2
  echo "Run: git fetch --unshallow" >&2
  exit 1
fi

